public class Migration72_73Test extends BrambleTestCase {

	static final String[] NEW_TABLES = {"contactLinks", "requestAccount",
			"outgoingRequests", "incomingRequests", "requestReplay",
			"requestBlocks"};

	private final File testDir = getTestDirectory();
	private final SecretKey key = getSecretKey();
	private final DatabaseTypes hyperSqlTypes = new DatabaseTypes(
			"BINARY(32)", "BINARY(32)", "BINARY",
			"INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY(START WITH 1)",
			"VARCHAR");

	@Before
	public void setUp() {
		assumeTrue(isCryptoStrengthUnlimited());
		assertTrue(testDir.mkdirs());
	}

	@After
	public void tearDown() {
		deleteTestDirectory(testDir);
	}

	private HyperSqlDatabase newDatabase() {
		return new HyperSqlDatabase(new TestDatabaseConfig(testDir),
				new TestMessageFactory(), new SystemClock());
	}

	@Test
	public void aVersion72DatabaseMigratesAndKeepsItsPendingContacts()
			throws Exception {
		byte[] pendingId = getRandomId();
		byte[] blob = getRandomBytes(64);
		HyperSqlDatabase db = newDatabase();
		db.open(key, null);
		Connection txn = db.startTransaction();
		downgradeTo72(txn, pendingId, blob);
		Settings s = new Settings();
		s.putInt(SCHEMA_VERSION_KEY, 72);
		db.mergeSettings(txn, s, DB_SETTINGS_NAMESPACE);
		db.commitTransaction(txn);
		db.close();

		db = newDatabase();
		assertTrue(db.open(key, null));
		txn = db.startTransaction();
		assertEquals(73, db.getSettings(txn, DB_SETTINGS_NAMESPACE)
				.getInt(SCHEMA_VERSION_KEY, -1));
		for (int run = 0; run < 2; run++) {
			new Migration72_73(hyperSqlTypes).migrate(txn);
			Collection<PendingContact> pending = db.getPendingContacts(txn);
			assertEquals("run " + run, 1, pending.size());
			PendingContact p = pending.iterator().next();
			assertArrayEquals(pendingId, p.getId().getBytes());
			assertArrayEquals(blob, p.getPublicKey().getEncoded());
			assertEquals(0, p.getExpiry());
			assertEquals(0, p.getRendezvousMode());
			assertTrue(db.getContactLinks(txn).isEmpty());
		}
		assertTrue(replayIndexes(txn).contains("REQUESTREPLAYBYONETIMEKEY"));
		assertTrue(replayIndexes(txn).contains("REQUESTREPLAYBYLINK"));
		exerciseNewTables(db, txn);
		db.commitTransaction(txn);
		db.close();
	}

	static java.util.Set<String> replayIndexes(Connection txn)
			throws Exception {
		java.util.Set<String> names = new java.util.HashSet<>();
		PreparedStatement ps = txn.prepareStatement("SELECT INDEX_NAME FROM"
				+ " INFORMATION_SCHEMA.SYSTEM_INDEXINFO"
				+ " WHERE TABLE_NAME = 'REQUESTREPLAY'");
		java.sql.ResultSet rs = ps.executeQuery();
		while (rs.next()) names.add(rs.getString(1).toUpperCase());
		rs.close();
		ps.close();
		return names;
	}

	@Test
	public void aNewDatabaseHasTheNewTablesAndColumns() throws Exception {
		HyperSqlDatabase db = newDatabase();
		assertFalse(db.open(key, null));
		Connection txn = db.startTransaction();
		PendingContact p = new PendingContact(
				new PendingContactId(getRandomId()),
				new HybridCommitmentPublicKey(getRandomBytes(64)), "alias",
				1000, 1, 5000, 2);
		db.addPendingContact(txn, p);
		PendingContact read = db.getPendingContact(txn, p.getId());
		assertEquals(5000, read.getExpiry());
		assertEquals(2, read.getRendezvousMode());
		assertTrue(replayIndexes(txn).contains("REQUESTREPLAYBYONETIMEKEY"));
		new Migration72_73(hyperSqlTypes).migrate(txn);
		assertTrue(replayIndexes(txn).contains("REQUESTREPLAYBYLINK"));
		exerciseNewTables(db, txn);
		db.commitTransaction(txn);
		db.close();
	}

	static void downgradeTo72(Connection txn, byte[] pendingId, byte[] blob)
			throws Exception {
		Statement st = txn.createStatement();
		for (String table : NEW_TABLES) st.execute("DROP TABLE " + table);
		st.execute("ALTER TABLE pendingContacts DROP COLUMN expiry");
		st.execute("ALTER TABLE pendingContacts DROP COLUMN rendezvousMode");
		st.close();
		PreparedStatement ps = txn.prepareStatement("INSERT INTO"
				+ " pendingContacts (pendingContactId, publicKey, alias,"
				+ " timestamp, formatVersion) VALUES (?, ?, ?, ?, ?)");
		ps.setBytes(1, pendingId);
		ps.setBytes(2, blob);
		ps.setString(3, "old");
		ps.setLong(4, 1234);
		ps.setInt(5, 1);
		assertEquals(1, ps.executeUpdate());
		ps.close();
	}

	static void exerciseNewTables(Database<Connection> db, Connection txn)
			throws Exception {
		AuthorId local = new AuthorId(getRandomId());
		byte[] linkId = getRandomId();
		ContactLink link = new ContactLink(linkId, local,
				ContactLink.KIND_ZERO_ID, ContactLink.STATE_ACTIVE, null,
				getRandomBytes(1216), getRandomBytes(2432), getRandomBytes(32),
				10, 0, 0, 0);
		db.addContactLink(txn, link);
		db.updateContactLink(txn, link.withLastSharedAt(20).retired(30));
		ContactLink read = db.getContactLinks(txn).iterator().next();
		assertArrayEquals(linkId, read.getLinkId());
		assertEquals(20, read.getLastSharedAt());
		assertEquals(30, read.getRetiredAt());
		assertEquals(0, read.getWithdrawnAt());
		assertEquals(ContactLink.STATE_RETIRED, read.getState());
		assertNull(read.getLabel());
		assertEquals(2432, read.getHybridPrivateKey().length);

		assertNull(db.getRequestAccountSecret(txn, local));
		byte[] secret = getRandomBytes(32);
		db.setRequestAccountSecret(txn, local, secret);
		db.setRequestAccountSecret(txn, local, secret);
		assertArrayEquals(secret, db.getRequestAccountSecret(txn, local));

		byte[] requestId = getRandomBytes(16);
		OutgoingRequest out = new OutgoingRequest(requestId, local,
				"zerion://x", "alias", "shown", null, getRandomBytes(1216),
				getRandomBytes(2432), 5, OutgoingRequest.STATE_QUEUED, 0, 5, 0,
				null, 0);
		db.addOutgoingRequest(txn, out);
		PendingContactId p = new PendingContactId(getRandomId());
		db.updateOutgoingRequest(txn, out.delivered(7, p));
		OutgoingRequest outRead = db.getOutgoingRequests(txn).iterator().next();
		assertEquals(OutgoingRequest.STATE_DELIVERED, outRead.getState());
		assertEquals(p, outRead.getPendingContactId());
		assertEquals(7, outRead.getDeliveredAt());
		assertArrayEquals(requestId, outRead.getRequestId());
		db.updateOutgoingRequest(txn,
				outRead.ended(OutgoingRequest.STATE_NO_ANSWER));
		outRead = db.getOutgoingRequests(txn).iterator().next();
		assertNull(outRead.getOneTimePrivateKey());
		assertNull(outRead.getPendingContactId());
		db.removeOutgoingRequest(txn, requestId);
		assertTrue(db.getOutgoingRequests(txn).isEmpty());

		IncomingRequest in = new IncomingRequest(requestId, linkId,
				getRandomBytes(65), "name", "note", getRandomBytes(32), 3, 4,
				IncomingRequest.STATE_RECEIVED, 0, null);
		db.addIncomingRequest(txn, in);
		db.updateIncomingRequest(txn, in.accepted(9, p));
		IncomingRequest inRead = db.getIncomingRequests(txn).iterator().next();
		assertNull(inRead.getName());
		assertNull(inRead.getNote());
		assertEquals(9, inRead.getAcceptedAt());
		assertEquals(p, inRead.getPendingContactId());
		db.removeIncomingRequest(txn, requestId);
		assertTrue(db.getIncomingRequests(txn).isEmpty());

		byte[] hash = getRandomId(), otk = getRandomId();
		db.addRequestReplay(txn, hash, 1, otk, linkId, 100);
		db.addRequestReplay(txn, hash, 2, null, linkId, 200);
		assertTrue(db.containsRequestReplay(txn, hash, 1));
		assertTrue(db.containsRequestReplay(txn, hash, 2));
		assertFalse(db.containsOneTimeKey(txn, otk, hash));
		assertTrue(db.containsOneTimeKey(txn, otk, getRandomId()));
		db.removeExpiredRequestReplay(txn, 100);
		assertFalse(db.containsRequestReplay(txn, hash, 1));
		assertTrue(db.containsRequestReplay(txn, hash, 2));

		byte[] tag = getRandomId();
		db.addRequestBlock(txn, linkId, tag, 1);
		db.addRequestBlock(txn, linkId, tag, 2);
		assertTrue(db.containsRequestBlock(txn, linkId, tag));
		assertFalse(db.containsRequestBlock(txn, getRandomId(), tag));
		List<byte[]> tags = new ArrayList<>(db.getRequestBlocks(txn, linkId));
		assertEquals(1, tags.size());
		db.removeRequestBlocks(txn, linkId);
		assertFalse(db.containsRequestBlock(txn, linkId, tag));

		db.removeContactLink(txn, linkId);
		assertTrue(db.getContactLinks(txn).isEmpty());
	}
}
